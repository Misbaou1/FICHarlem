#!/usr/bin/env python3
"""Build an embeddable copy of the registration form.

The standalone page owns the whole document, so its CSS can use :root, html,
body and plain class names like .card and .field. Dropped into an existing
page those would collide both ways, so this generates a version where every
selector is scoped under .futa-reg.

rem units are converted to px on the way through: rem resolves against <html>,
which the embed must not touch, so leaving them in would make every size depend
on whatever the host page happens to set.

    python3 build-embed.py     ->  embed/registration.css, embed/registration.html
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'embed')
SCOPE = '.futa-reg'
BASE_PX = 18.5          # the standalone page's html font-size

# selectors that mean "the document" and become the wrapper itself
ROOT_SELECTORS = {':root', 'html', 'body', 'html, body', '*'}


def rem_to_px(css):
    def swap(m):
        px = float(m.group(1)) * BASE_PX
        return ('%.2f' % px).rstrip('0').rstrip('.') + 'px'
    return re.sub(r'(-?\d*\.?\d+)rem\b', swap, css)


def scope_selector(sel):
    sel = sel.strip()
    if not sel or sel.startswith('@'):
        return sel

    parts = []
    for one in sel.split(','):
        one = one.strip()
        if not one:
            continue
        if one in ROOT_SELECTORS:
            parts.append(SCOPE if one != '*' else SCOPE + ' *')
        elif one.startswith(':focus-visible'):
            parts.append(SCOPE + ' ' + one)
        else:
            parts.append(SCOPE + ' ' + one)
    return ', '.join(parts)


def scope_css(css):
    out, i = [], 0
    while i < len(css):
        # Skip past whitespace before deciding what comes next. Checking for a
        # comment at i alone misses one that follows a newline, and it then
        # gets swallowed into the next rule's selector.
        j = i
        while j < len(css) and css[j] in ' \t\r\n':
            j += 1
        if j >= len(css):
            out.append(css[i:])
            break
        if css.startswith('/*', j):
            end = css.find('*/', j) + 2
            out.append(css[i:end])
            i = end
            continue

        brace = css.find('{', i)
        if brace == -1:
            out.append(css[i:])
            break

        prelude = css[i:brace]
        head = prelude.strip()

        if head.startswith('@'):
            # at-rule with a block of its own rules: recurse into it
            depth, j = 0, brace
            while j < len(css):
                if css[j] == '{': depth += 1
                elif css[j] == '}':
                    depth -= 1
                    if depth == 0: break
                j += 1
            inner = css[brace + 1:j]
            if head.split()[0] in ('@media', '@supports'):
                out.append(prelude + '{' + scope_css(inner) + '}')
            else:
                out.append(prelude + '{' + inner + '}')     # @keyframes etc
            i = j + 1
            continue

        close = css.find('}', brace)
        body = css[brace + 1:close]
        out.append(prelude.replace(head, scope_selector(head)) + '{' + body + '}')
        i = close + 1

    return ''.join(out)


def verify_scoped(css):
    """Refuse to emit CSS that could style the page it is dropped into."""
    stripped = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    loose = []
    for m in re.finditer(r'(^|[}])\s*([^{}@]+)\{', stripped):
        for one in m.group(2).split(','):
            one = one.strip()
            if one and not one.startswith(SCOPE):
                loose.append(one)
    if loose:
        raise SystemExit('unscoped selectors would leak into the host page:\n  ' +
                         '\n  '.join(loose[:10]))
    if re.search(r'\d(?:\.\d+)?rem\b', stripped):
        raise SystemExit('rem units left in the embed build')
    print('scope check passed')


def main():
    os.makedirs(OUT, exist_ok=True)

    css = open(os.path.join(HERE, 'styles.css')).read()
    scoped = scope_css(rem_to_px(css))
    # the wrapper carries the base size itself now that html is off limits
    scoped = (SCOPE + '{font-size:%gpx;line-height:1.5;text-align:left;}\n' % BASE_PX) + scoped
    verify_scoped(scoped)
    open(os.path.join(OUT, 'registration.css'), 'w').write(scoped)

    html = open(os.path.join(HERE, 'index.html')).read()

    sprite = html[html.index('<svg class="sprite"'):html.index('</svg>', html.index('<svg class="sprite"')) + 6]
    body = html[html.index('<div class="langbar">'):html.index('</main>') + len('</main>')]
    tpl = html[html.index('<template id="studentTemplate">'):html.index('</template>') + len('</template>')]

    embed = ('<!-- FUTA Islamic School registration form.\n'
             '     Generated by build-embed.py - edit the source in ../ and rebuild. -->\n'
             '<div class="futa-reg">\n' + sprite + '\n' + body + '\n' + tpl + '\n</div>\n')
    open(os.path.join(OUT, 'registration.html'), 'w').write(embed)

    print('embed/registration.css   %6d bytes' % len(scoped))
    print('embed/registration.html  %6d bytes' % len(embed))


if __name__ == '__main__':
    main()
